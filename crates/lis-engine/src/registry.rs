//! The single registry of every IPC command: its Tauri name, the action name
//! for log lines and denial events, and who may call it (REQ-IDN-003, NFR-08,
//! NFR-31). The table-driven authorization test runs over [`COMMANDS`], and
//! the desktop shell checks its capability file against it.

mod authentication;
pub(crate) use authentication::*;

mod access;
pub use access::Access;

/// One IPC command.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CommandSpec {
    /// The Tauri command name.
    pub name: &'static str,
    /// `<module>.<verb>`, for log lines and denial events.
    pub action: &'static str,
    /// Who may call it.
    pub access: Access,
}

pub(crate) const fn spec(name: &'static str, action: &'static str, access: Access) -> CommandSpec {
    CommandSpec {
        name,
        action,
        access,
    }
}

